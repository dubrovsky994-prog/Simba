const FALLBACK_BENEFIT = 'Снимает часть ручной работы и помогает не терять клиентов.'

export function recommendationBenefit(niche: NicheKey, label: string): string {
  return BENEFITS[niche]?.[label] ?? FALLBACK_BENEFIT
}

// Small, generic icon per recommendation, picked by keyword — not meant to be
// exhaustive, just enough visual variety without inventing a bespoke icon set.
export function recommendationIcon(label: string) {
  const l = label.toLowerCase()
  if (l.includes('запис') || l.includes('расписан') || l.includes('календар') || l.includes('замер') || l.includes('бриф') || l.includes('пакет'))
    return IconApp
  if (l.includes('оплат') || l.includes('стоимост') || l.includes('расчёт') || l.includes('предложение'))
    return IconChart
  if (l.includes('crm') || l.includes('база') || l.includes('клиент') || l.includes('учёт') || l.includes('карточка') || l.includes('ученик'))
    return IconUsers
  if (l.includes('напомина') || l.includes('уведомлен') || l.includes('подтвержд') || l.includes('ответ'))
    return IconBot
  if (l.includes('заказ') || l.includes('корзин') || l.includes('каталог') || l.includes('меню') || l.includes('доставк') || l.includes('покупк'))
    return IconPackage
  if (l.includes('приём') || l.includes('анкет') || l.includes('фото'))
    return IconInbox
  return IconCheckSmall
}
